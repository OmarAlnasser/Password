#!/usr/bin/env python3
"""Generate lib/l10n/app_localizations_ar_ltr.dart.

By default the app keeps its left-to-right layout in Arabic (see
`AppSettings.mirrorArabic`). A left-to-right paragraph would put the full stop
of an Arabic sentence, or the number in "3 items", on the wrong side, so in
that mode every Arabic string is wrapped in a right-to-left isolate
(U+2067 ... U+2069). The generated class does that by overriding each member
of AppLocalizationsAr.

Run it after `flutter gen-l10n` whenever a string is added or removed:

    python3 tool/gen_arabic_ltr.py

test/l10n/arabic_ltr_test.dart fails when a string is missing from it.
"""

import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'lib' / 'l10n' / 'app_localizations.dart'
OUT = ROOT / 'lib' / 'l10n' / 'app_localizations_ar_ltr.dart'

# Strings that are data, not text to show: they must stay byte-identical.
#   appTitle: the window title.
#   resetConfirmWord: compared with what the user types.
KEEP = {'appTitle', 'resetConfirmWord'}

GETTER = re.compile(r'^  String get (\w+);$')
METHOD = re.compile(r'^  String (\w+)\(([^)]*)\);$')


def members(source: str):
    out = []
    for line in source.splitlines():
        m = GETTER.match(line)
        if m:
            out.append((m.group(1), None))
            continue
        m = METHOD.match(line)
        if m:
            params = [p.strip() for p in m.group(2).split(',') if p.strip()]
            for p in params:
                if not re.fullmatch(r'[\w<>?]+ \w+', p):
                    raise SystemExit(f'unsupported parameter list in {m.group(1)}: {m.group(2)}')
            out.append((m.group(1), params))
    return out


def render(items) -> str:
    lines = [
        '// Generated by tool/gen_arabic_ltr.py from app_localizations.dart.',
        '// Do not edit by hand: run `python3 tool/gen_arabic_ltr.py`.',
        '',
        "import 'app_localizations_ar.dart';",
        '',
        '/// The Arabic strings for the left-to-right layout: each one sits in a',
        '/// right-to-left isolate, so its punctuation and numbers stay in place.',
        'class AppLocalizationsArLtr extends AppLocalizationsAr {',
        '  AppLocalizationsArLtr();',
        '',
    ]
    for name, params in items:
        if name in KEEP:
            continue
        lines.append('  @override')
        if params is None:
            lines.append(f'  String get {name} => _rtl(super.{name});')
        else:
            names = ', '.join(p.split(' ')[-1] for p in params)
            lines.append(f'  String {name}({", ".join(params)}) =>')
            lines.append(f'      _rtl(super.{name}({names}));')
        lines.append('')
    lines[-1] = '}'
    lines += [
        '',
        "String _rtl(String s) => s.isEmpty ? s : '\\u2067$s\\u2069';",
        '',
    ]
    return '\n'.join(lines)


def main() -> int:
    items = members(SOURCE.read_text(encoding='utf-8'))
    if not items:
        raise SystemExit(f'no members found in {SOURCE}')
    OUT.write_text(render(items), encoding='utf-8')
    dart = shutil.which('dart')
    if dart is None:
        print('dart not found: run `dart format lib/l10n` before committing.')
    else:
        subprocess.run([dart, 'format', str(OUT)], check=True,
                       stdout=subprocess.DEVNULL)
    print(f'Wrote {OUT.relative_to(ROOT)} ({len(items) - len(KEEP & {n for n, _ in items})} strings).')
    return 0


if __name__ == '__main__':
    sys.exit(main())
